export function generateSampleProductsForCategories(
  selectedCategoryNames: string[],
  storeId: string
): Product[] {
  const products: Product[] = [];
  const now = new Date().toISOString();

  selectedCategoryNames.forEach((catName) => {
    const samples = CATEGORY_SAMPLE_PRODUCTS[catName] || CATEGORY_SAMPLE_PRODUCTS['Home and Living'];
    samples.forEach((sample, idx) => {
      const slug = sample.name
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/(^-|-$)+/g, '');

      products.push({
        id: `prod-${storeId}-${catName.slice(0, 3).toLowerCase()}-${idx + 1}-${Date.now() % 10000}`,
        storeId,
        name: sample.name,
        slug,
        description: sample.description,
        price: sample.price,
        compareAtPrice: sample.compareAtPrice,
        sku: `${sample.skuPrefix}-${100 + idx}`,
        category: catName,
        images: sample.images,
        variants: sample.variants,
        stockQuantity: sample.stock,
        lowStockThreshold: sample.lowStockThreshold,
        isPublished: true,
        createdAt: now,
        updatedAt: now,
      });
    });
  });

  return products;
}

